def sigmoid(x: np.ndarray) -> np.ndarray:
    return 1 / (1 + np.exp(-x))


def generate_transactions(n: int = 12000, seed: int = RANDOM_STATE) -> pd.DataFrame:
    """Генерация модельных обезличенных транзакций с нелинейными и скрытыми паттернами."""
    rng = np.random.default_rng(seed)
    start = pd.Timestamp("2026-01-01")
    days = rng.integers(0, 90, size=n)
    seconds = rng.integers(0, 24 * 3600, size=n)
    timestamps = start + pd.to_timedelta(days, unit="D") + pd.to_timedelta(seconds, unit="s")
    timestamps = pd.Series(timestamps).sort_values().reset_index(drop=True)

    player_count = 1650
    player_ids = rng.integers(1, player_count + 1, size=n)
    player_hash = [f"plr_{x:05d}" for x in player_ids]
    latent_player_risk = rng.beta(a=1.4, b=8.5, size=player_count + 1)
    hidden_risk = latent_player_risk[player_ids]

    channel = rng.choice(["card", "e_wallet", "bank_transfer", "crypto_pvt"], size=n, p=[0.53, 0.21, 0.16, 0.10])
    operation_type = rng.choice(["deposit", "withdrawal", "refund"], size=n, p=[0.72, 0.22, 0.06])

    base_amount = rng.lognormal(mean=4.22, sigma=0.98, size=n)
    multiplier = np.where(operation_type == "withdrawal", 1.7, 1.0)
    multiplier *= np.where(channel == "crypto_pvt", 1.35, 1.0)
    amount_byn = np.clip(base_amount * multiplier, 10, 8500).round(2)

    hour = timestamps.dt.hour.to_numpy()
    day_of_week = timestamps.dt.dayofweek.to_numpy()
    is_weekend = (day_of_week >= 5).astype(int)
    is_night = ((hour < 6) | (hour >= 23)).astype(int)
    is_crypto = (channel == "crypto_pvt").astype(int)
    is_withdrawal = (operation_type == "withdrawal").astype(int)
    is_refund = (operation_type == "refund").astype(int)

    daily_tx_count = rng.poisson(lam=2.0 + 1.1 * is_weekend + 0.7 * is_crypto + 0.9 * hidden_risk, size=n) + 1
    previous_failed_cnt = rng.poisson(lam=0.14 + 0.36 * is_crypto + 0.25 * is_night + 0.8 * hidden_risk, size=n)
    account_age_days = rng.gamma(shape=2.8, scale=53, size=n).astype(int) + 1
    is_new_player = (account_age_days < 14).astype(int)
    kyc_score = np.clip(
        rng.normal(loc=0.86, scale=0.13, size=n) - 0.10 * is_new_player - 0.06 * is_crypto - 0.18 * hidden_risk,
        0.20,
        1.0,
    )

    # Latency is observable, but includes hidden operational shocks and bursts.
    burst_day = np.isin(days, rng.choice(np.arange(90), size=8, replace=False)).astype(int)
    latency_sec = (
        rng.gamma(shape=2.3, scale=28, size=n)
        + np.where(channel == "bank_transfer", 105, 0)
        + np.where(channel == "crypto_pvt", 175, 0)
        + np.where(previous_failed_cnt > 1, 80, 0)
        + np.where(is_withdrawal == 1, 58, 0)
        + np.where(burst_day == 1, rng.gamma(2.0, 55, n), 0)
    )
    latency_sec = np.clip(latency_sec, 5, 2800).round(0).astype(int)

    commission_rate = np.select(
        [channel == "card", channel == "e_wallet", channel == "bank_transfer", channel == "crypto_pvt"],
        [0.027, 0.018, 0.012, 0.0045],
        default=0.02,
    )
    commission_byn = (amount_byn * commission_rate).round(2)

    # Target label is generated by a noisy nonlinear mechanism. Several latent components are intentionally not in X.
    amount_high = (amount_byn > np.quantile(amount_byn, 0.86)).astype(int)
    amount_extreme = (amount_byn > np.quantile(amount_byn, 0.96)).astype(int)
    velocity_flag = ((daily_tx_count >= 6) & (previous_failed_cnt >= 1)).astype(int)
    crypto_withdrawal = ((is_crypto == 1) & (is_withdrawal == 1)).astype(int)
    night_new_player = ((is_night == 1) & (is_new_player == 1)).astype(int)
    low_kyc_large = ((kyc_score < 0.68) & (amount_byn > 900)).astype(int)
    hidden_cluster = ((hidden_risk > 0.24) & ((is_crypto == 1) | (is_refund == 1))).astype(int)
    operational_shock = ((latency_sec > 430) & (burst_day == 1)).astype(int)

    nonlinear_score = (
        0.55 * amount_high
        + 0.85 * amount_extreme
        + 1.20 * velocity_flag
        + 1.05 * crypto_withdrawal
        + 0.90 * night_new_player
        + 1.10 * low_kyc_large
        + 1.35 * hidden_cluster
        + 0.70 * operational_shock
        + 0.65 * is_refund
        + 0.45 * is_crypto
        + 0.35 * is_night
        + 0.18 * np.log1p(amount_byn)
        - 1.65 * kyc_score
        + rng.normal(0, 0.95, n)
    )
    risk_probability = sigmoid(-3.00 + nonlinear_score)
    manual_review = rng.binomial(1, risk_probability)

    status = np.where(manual_review == 1, "manual_review", "confirmed")
    technical_decline = (rng.random(n) < (0.022 + 0.025 * (channel == "bank_transfer") + 0.015 * burst_day)) & (manual_review == 0)
    status = np.where(technical_decline, "declined", status)

    df = pd.DataFrame(
        {
            "transaction_id": [f"tx_{i + 1:06d}" for i in range(n)],
            "player_hash": player_hash,
            "timestamp": timestamps,
            "channel": channel,
            "operation_type": operation_type,
            "amount_byn": amount_byn,
            "hour": hour,
            "day_of_week": day_of_week,
            "is_weekend": is_weekend,
            "is_night": is_night,
            "is_crypto": is_crypto,
            "account_age_days": account_age_days,
            "is_new_player": is_new_player,
            "kyc_score": np.round(kyc_score, 3),
            "daily_tx_count": daily_tx_count,
            "previous_failed_cnt": previous_failed_cnt,
            "latency_sec": latency_sec,
            "commission_rate": commission_rate,
            "commission_byn": commission_byn,
            "status": status,
            "manual_review": manual_review,
        }
    )
    df["date"] = df["timestamp"].dt.date.astype(str)
    return df


def prepare_xy(df: pd.DataFrame) -> Tuple[pd.DataFrame, pd.Series, List[str], List[str]]:
    features = [
        "channel",
        "operation_type",
        "amount_byn",
        "hour",
        "day_of_week",
        "is_weekend",
        "is_night",
        "is_crypto",
        "account_age_days",
        "is_new_player",
        "kyc_score",
        "daily_tx_count",
        "previous_failed_cnt",
        "latency_sec",
        "commission_rate",
    ]
    X = df[features]
    y = df["manual_review"]
    categorical = ["channel", "operation_type"]
    numeric = [x for x in features if x not in categorical]
    return X, y, categorical, numeric


def chronological_split(df: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    df_sorted = df.sort_values("timestamp").reset_index(drop=True)
    n = len(df_sorted)
    cut_train = int(n * 0.60)
    cut_val = int(n * 0.80)
    return df_sorted.iloc[:cut_train].copy(), df_sorted.iloc[cut_train:cut_val].copy(), df_sorted.iloc[cut_val:].copy()


def build_preprocessor(categorical: List[str], numeric: List[str]) -> ColumnTransformer:
    return ColumnTransformer(
        transformers=[
            ("cat", OneHotEncoder(handle_unknown="ignore"), categorical),
            ("num", StandardScaler(), numeric),
        ]
    )


def find_best_threshold(y_true: pd.Series, proba: np.ndarray, beta: float = 2.0) -> Dict[str, float]:
    thresholds = np.linspace(0.05, 0.95, 181)
    rows = []
    for thr in thresholds:
        pred = (proba >= thr).astype(int)
        rows.append(
            {
                "threshold": thr,
                "precision": precision_score(y_true, pred, zero_division=0),
                "recall": recall_score(y_true, pred, zero_division=0),
                "f1": f1_score(y_true, pred, zero_division=0),
                "f2": fbeta_score(y_true, pred, beta=beta, zero_division=0),
                "review_count": int(pred.sum()),
            }
        )
    table = pd.DataFrame(rows)
    best = table.loc[table["f2"].idxmax()].to_dict()
    return {k: float(v) for k, v in best.items()}


def evaluate_on_test(name: str, proba: np.ndarray, y_test: pd.Series, threshold: float) -> Dict[str, float]:
    pred = (proba >= threshold).astype(int)
    return {
        "model": name,
        "threshold_from_validation": round(threshold, 3),
        "roc_auc": round(roc_auc_score(y_test, proba), 3),
        "pr_auc": round(average_precision_score(y_test, proba), 3),
        "accuracy": round(accuracy_score(y_test, pred), 3),
        "precision": round(precision_score(y_test, pred, zero_division=0), 3),
        "recall": round(recall_score(y_test, pred, zero_division=0), 3),
        "f1": round(f1_score(y_test, pred, zero_division=0), 3),
        "f2": round(fbeta_score(y_test, pred, beta=2, zero_division=0), 3),
        "review_count": int(pred.sum()),
    }


def time_series_cv_scores(pipe: Pipeline, X_train: pd.DataFrame, y_train: pd.Series, name: str) -> Dict[str, float]:
    """Small TimeSeriesSplit check without heavy hyperparameter search."""
    rows = []
    tscv = TimeSeriesSplit(n_splits=3)
    for fold, (tr, va) in enumerate(tscv.split(X_train), start=1):
        model = pipe
        model.fit(X_train.iloc[tr], y_train.iloc[tr])
        proba = model.predict_proba(X_train.iloc[va])[:, 1]
        pred = (proba >= 0.5).astype(int)
        rows.append({
            "model": name,
            "fold": fold,
            "roc_auc": roc_auc_score(y_train.iloc[va], proba),
            "f1": f1_score(y_train.iloc[va], pred, zero_division=0),
            "f2": fbeta_score(y_train.iloc[va], pred, beta=2, zero_division=0),
        })
    df = pd.DataFrame(rows)
    return {
        "model": name,
        "cv_roc_auc_mean": df["roc_auc"].mean(),
        "cv_f1_mean": df["f1"].mean(),
        "cv_f2_mean": df["f2"].mean(),
    }


def train_models(df: pd.DataFrame) -> Dict[str, object]:
    train_df, val_df, test_df = chronological_split(df)
    X_train, y_train, categorical, numeric = prepare_xy(train_df)
    X_val, y_val, _, _ = prepare_xy(val_df)
    X_test, y_test, _, _ = prepare_xy(test_df)
    preprocessor = build_preprocessor(categorical, numeric)

    models: Dict[str, Pipeline] = {
        "LogisticRegression": Pipeline([("prep", preprocessor), ("clf", LogisticRegression(max_iter=1200, class_weight="balanced", random_state=RANDOM_STATE))]),
        "RandomForest": Pipeline([("prep", preprocessor), ("clf", RandomForestClassifier(n_estimators=90, max_depth=10, min_samples_leaf=6, class_weight="balanced", random_state=RANDOM_STATE, n_jobs=1))]),
        "GradientBoosting": Pipeline([("prep", preprocessor), ("clf", GradientBoostingClassifier(n_estimators=100, learning_rate=0.06, max_depth=2, random_state=RANDOM_STATE))]),
    }
    try:
        from imblearn.pipeline import Pipeline as ImbPipeline
        from imblearn.over_sampling import SMOTE
        models["LogisticRegression_SMOTE"] = ImbPipeline([("prep", preprocessor), ("smote", SMOTE(random_state=RANDOM_STATE, k_neighbors=5)), ("clf", LogisticRegression(max_iter=1200, random_state=RANDOM_STATE))])
    except Exception:
        pass

    cv_rows = []
    metrics_rows = []
    validation_rows = []
    fitted: Dict[str, Pipeline] = {}
    thresholds: Dict[str, float] = {}
    for name, pipe in models.items():
        cv_rows.append(time_series_cv_scores(pipe, X_train, y_train, name))
        pipe.fit(X_train, y_train)
        fitted[name] = pipe
        val_proba = pipe.predict_proba(X_val)[:, 1]
        best = find_best_threshold(y_val, val_proba, beta=2)
        thresholds[name] = best["threshold"]
        best["model"] = name
        validation_rows.append(best)
        test_proba = pipe.predict_proba(X_test)[:, 1]
        metrics_rows.append(evaluate_on_test(name, test_proba, y_test, thresholds[name]))

    cv_df = pd.DataFrame(cv_rows).sort_values("cv_f2_mean", ascending=False)
    metrics_df = pd.DataFrame(metrics_rows).sort_values(["f2", "roc_auc"], ascending=False)
    val_thresholds_df = pd.DataFrame(validation_rows).sort_values(["f2"], ascending=False)
    cv_df.to_csv(OUT_DIR / "timeseries_cv_scores.csv", index=False)
    metrics_df.to_csv(OUT_DIR / "model_metrics.csv", index=False)
    val_thresholds_df.to_csv(OUT_DIR / "validation_thresholds.csv", index=False)

    best_name = metrics_df.iloc[0]["model"]
    best_model = fitted[best_name]
    best_threshold = thresholds[best_name]
    best_proba = best_model.predict_proba(X_test)[:, 1]
    best_pred = (best_proba >= best_threshold).astype(int)

    return {
        "train_df": train_df,
        "val_df": val_df,
        "test_df": test_df,
        "X_train": X_train,
        "y_train": y_train,
        "X_val": X_val,
        "y_val": y_val,
        "X_test": X_test,
        "y_test": y_test,
        "models": fitted,
        "thresholds": thresholds,
        "cv_df": cv_df,
        "metrics_df": metrics_df,
        "validation_thresholds_df": val_thresholds_df,
        "best_name": best_name,
        "best_model": best_model,
        "best_threshold": best_threshold,
        "best_proba": best_proba,
        "best_pred": best_pred,
        "categorical": categorical,
        "numeric": numeric,
    }


