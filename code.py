def erlang_c(lambda_rate: float, mu: float, servers: int) -> Tuple[float, float, float, float]:
    """Return rho, P(wait), Wq hours, Lq for M/M/c. If unstable, return infinities."""
    if lambda_rate <= 0:
        return 0.0, 0.0, 0.0, 0.0
    a = lambda_rate / mu
    rho = lambda_rate / (servers * mu)
    if rho >= 1:
        return rho, 1.0, float("inf"), float("inf")
    denom = sum((a ** n) / math.factorial(n) for n in range(servers)) + (a ** servers) / (math.factorial(servers) * (1 - rho))
    p0 = 1 / denom
    p_wait = (a ** servers) / (math.factorial(servers) * (1 - rho)) * p0
    wq = p_wait / (servers * mu - lambda_rate)
    lq = lambda_rate * wq
    return rho, p_wait, wq, lq


def queue_analysis(sensitivity_df: pd.DataFrame, test_df: pd.DataFrame) -> pd.DataFrame:
    # test period length in days
    days = pd.to_datetime(test_df["date"]).nunique()
    service_time_min = 6.0
    mu = 60.0 / service_time_min
    peak_multiplier = 3.0
    rows = []
    for _, row in sensitivity_df.iterrows():
        daily_reviews = row["review_count"] / max(days, 1)
        lambda_hour = daily_reviews / 24.0 * peak_multiplier
        for c in [1, 2]:
            rho, p_wait, wq_h, lq = erlang_c(lambda_hour, mu, c)
            rows.append({
                "threshold": row["threshold"],
                "servers": c,
                "lambda_peak_hour": lambda_hour,
                "rho": rho,
                "p_wait": p_wait,
                "wq_minutes": wq_h * 60 if math.isfinite(wq_h) else np.inf,
                "lq": lq,
            })
    out = pd.DataFrame(rows)
    out.to_csv(OUT_DIR / "queue_analysis.csv", index=False)
    fig, ax = plt.subplots(figsize=(7.0, 4.2))
    for c, sub in out.groupby("servers"):
        ax.plot(sub["threshold"], sub["wq_minutes"], marker="o", label=f"{c} оператор(а)")
    ax.set_title("Оценка ожидания ручной проверки по модели M/M/c")
    ax.set_xlabel("Порог классификации")
    ax.set_ylabel("Среднее ожидание в очереди, мин")
    ax.legend()
    fig.tight_layout()
    fig.savefig(OUT_DIR / "fig_4_7_queue_waiting.png", dpi=220)
    plt.close(fig)
    return out


def cost_threshold_analysis(y_test: pd.Series, proba: np.ndarray) -> pd.DataFrame:
    c_fp = 4.0      # cost of unnecessary manual review, BYN
    c_fn = 250.0    # expected cost of missed high-risk transaction, BYN
    thresholds = np.linspace(0.10, 0.90, 17)
    rows = []
    for thr in thresholds:
        pred = (proba >= thr).astype(int)
        cm = confusion_matrix(y_test, pred)
        tn, fp, fn, tp = cm.ravel()
        total_cost = fp * c_fp + fn * c_fn
        rows.append({
            "threshold": round(float(thr), 2),
            "fp": int(fp),
            "fn": int(fn),
            "manual_review": int(pred.sum()),
            "cost_byn": round(total_cost, 2),
        })
    out = pd.DataFrame(rows)
    out.to_csv(OUT_DIR / "cost_threshold.csv", index=False)
    fig, ax = plt.subplots(figsize=(7.0, 4.2))
    ax.plot(out["threshold"], out["cost_byn"], marker="o")
    best = out.loc[out["cost_byn"].idxmin()]
    ax.scatter([best["threshold"]], [best["cost_byn"]], s=80, zorder=4)
    ax.set_title("Суммарные издержки при разных порогах")
    ax.set_xlabel("Порог классификации")
    ax.set_ylabel("Издержки на тестовом периоде, BYN")
    fig.tight_layout()
